// Generate the offline demo from scenarios and sample extensions.
import { readFile, readdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
// Display order; other scenarios follow alphabetically.
const ORDER = [
  "lighting-control",
  "status-feedback",
  "shutter-control",
  "shutter-calibration",
  "shutter-calibrated",
  "scenes",
  "timers",
  "priority-control",
  "object-flags",
  "full-topology",
  "usb-interface",
  "dali-gateway",
  "room-heating",
  "dimming",
  "weather-protection",
  "air-quality",
  "tunable-white",
  "energy-metering",
  "venetian-blind",
  "time-schedule",
  "push-button-interface",
  "bus-voltage",
  "alarms",
  "heat-pump",
  "heating-cooling",
  "scene-learning",
];
const rank = (n) => (ORDER.includes(n) ? ORDER.indexOf(n) : ORDER.length);
const names = (await readdir(resolve(root, "scenarios")))
  .filter((f) => f.endsWith(".json"))
  .map((f) => f.replace(/\.json$/, ""))
  .sort((a, b) => rank(a) - rank(b) || a.localeCompare(b));
const scenarios = new Map();
for (const n of names)
  scenarios.set(n, JSON.parse(await readFile(resolve(root, "scenarios", `${n}.json`), "utf8")));

// Extension examples: scenario and classic scripts loaded after the bundle.
const extensionExamples = [
  { id: "extension-delayed-switch", file: "site/samples/extensions/delayed-switch.json" },
];
const extensionScripts = ["delayed-switch.js", "led-lamp-view.js"];
for (const e of extensionExamples)
  scenarios.set(e.id, JSON.parse(await readFile(resolve(root, e.file), "utf8")));

// Offline demo: one section per scenario, followed by extension examples.
const section = (id, note = "") => `    <section>${note}
      <bus-diagram scenario="#scenario-${id}"></bus-diagram>
      <script type="application/json" id="scenario-${id}">
${JSON.stringify(scenarios.get(id), null, 2)}
      </script>
    </section>`;
const sections = [
  ...names.map((n) => section(n)),
  ...extensionExamples.map((e) =>
    section(
      e.id,
      `\n      <p class="note">Extension example: behavior and view are registered by <code>extensions/*.js</code>, loaded after the bundle.</p>`,
    ),
  ),
].join("\n");
const demo = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <link rel="icon" href="data:image/svg+xml,<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 32 32'><rect width='32' height='32' rx='7' fill='%231e9a6d'/><path d='M5 23h22' stroke='%23fff' stroke-width='3' stroke-linecap='round'/><rect x='7' y='8' width='7' height='9' rx='2' fill='%23fff2cc'/><rect x='18' y='8' width='7' height='9' rx='2' fill='%23fff2cc'/><path d='M10.5 17v6M21.5 17v6' stroke='%23fff' stroke-width='2'/></svg>" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>BusDiagram — offline examples</title>
    <!-- Generated by scripts/sync-scenarios.mjs; edit scenarios/ instead. -->
    <!-- Load the bundle and extensions before initializing the components. -->
    <script defer src="./bus-diagram.js"></script>
${extensionScripts.map((s) => `    <script defer src="./extensions/${s}"></script>`).join("\n")}
    <style>
      body { margin: 0; padding: 24px clamp(12px, 3vw, 40px); background: #fafaf7; color: #1c1e23; font-family: system-ui, sans-serif; }
      main { max-width: 1280px; margin: 0 auto; }
      h1 { font-size: 1.6rem; margin: 0 0 4px; }
      p { color: #5f646d; margin: 0 0 18px; }
      p.note { margin: 0 0 4px; font-size: 0.9rem; }
      section { margin-bottom: 40px; }
    </style>
  </head>
  <body>
    <main>
      <h1>BusDiagram</h1>
      <p>Diagrams of several independent installations. Select a device to inspect its objects (W/T flags) and channels. Press a push-button key to follow the resulting telegrams on the bus.</p>
${sections}
    </main>
  </body>
</html>
`;
await writeFile(resolve(root, "demo/offline.html"), demo);
console.log(`demo/offline.html : ${names.length} scenario(s), ${extensionExamples.length} extension example(s).`);
